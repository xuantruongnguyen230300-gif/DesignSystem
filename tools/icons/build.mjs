#!/usr/bin/env node
// Generate packages/ui/icon/src/icons.generated.ts from the curated list in packages/ui/icon/icons.json.
// Source: Tabler Icons outline nodes (MIT). Every outline icon is a list of <path> elements, so an
// icon is stored as path data — rendered by NxtIcon through the template (no innerHTML, CSP-safe).
// Usage: node tools/icons/build.mjs
import fs from 'node:fs';
import path from 'node:path';

const cfgFile = 'packages/ui/icon/icons.json';
const outFile = 'packages/ui/icon/src/icons.generated.ts';
const cfg = JSON.parse(fs.readFileSync(cfgFile, 'utf8'));
// Read from disk: the package's "exports" map does not expose these JSON files to require().
const readJson = (rel) => JSON.parse(fs.readFileSync(path.join('node_modules', rel), 'utf8'));
const source = readJson(cfg.source);
const tablerVersion = readJson('@tabler/icons/package.json').version;

const names = [...new Set(Object.values(cfg.icons).flat())].sort();
const missing = names.filter((n) => !source[n]);
if (missing.length) {
  console.error(`Unknown Tabler icon name(s): ${missing.join(', ')} — check https://tabler.io/icons`);
  process.exit(1);
}

const isFrame = (a) => a.d === 'M0 0h24v24H0z'; // Tabler's invisible bounding box
const entries = names.map((name) => {
  const paths = source[name]
    .filter(([tag, attrs]) => tag === 'path' && !isFrame(attrs))
    .map(([, attrs]) => {
      const extra = Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== 'd'));
      return Object.keys(extra).length ? { d: attrs.d, ...extra } : attrs.d;
    });
  return `  ${JSON.stringify(name)}: ${JSON.stringify(paths)},`;
});

const content = `// GENERATED by tools/icons/build.mjs from ${cfgFile} — do not edit.
// Icons: Tabler Icons ${tablerVersion} (MIT License, https://tabler.io/icons).

/** A path is its \`d\` string, or an object when it carries extra presentation attributes. */
export type NxtIconPath = string | { d: string; fill?: string; opacity?: string; stroke?: string };

export const NXT_ICONS = {
${entries.join('\n')}
} satisfies Record<string, NxtIconPath[]>;

/** Every icon name available in \`<nxt-icon name="…">\`. */
export type NxtIconName = keyof typeof NXT_ICONS;
`;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, content);
console.log(`icons: ${names.length} icons → ${outFile} (${(Buffer.byteLength(content) / 1024).toFixed(1)} KB, Tabler ${tablerVersion})`);
