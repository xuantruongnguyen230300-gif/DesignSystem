#!/usr/bin/env node
// Keeps the component catalog in packages/ui/README.md in step with the repo, so the README (the only documentation a visitor of
// the GitHub or package page sees) never forgets a component or lists one that was removed.
//
//   node tools/docs/readme-catalog.mjs           rewrite the block between the markers
//   node tools/docs/readme-catalog.mjs --check   exit 1 when the block is stale (part of `npm run ds:check`)
//
// One row per entry point of @nxt/ui (a folder of packages/ui with a public-api.ts). The description is the one of the docs page
// (apps/docs/src/content/components/<name>.md), the link goes to the component's SPEC.md on the default branch.

import fs from 'node:fs';
import path from 'node:path';

const README = 'packages/ui/README.md';
const BEGIN = '<!-- nxt-components:begin (generated by tools/docs/readme-catalog.mjs; run: npm run readme:catalog) -->';
const END = '<!-- nxt-components:end -->';

const GROUPS = [
  ['Hành động', ['button', 'menu', 'segmented']],
  ['Nhập liệu', ['form-field', 'checkbox', 'radio-group', 'switch', 'stepper', 'slider', 'combobox', 'date-picker', 'calendar', 'search', 'filter', 'value-help', 'view-manager']],
  ['Bố cục và khung trang', ['layout', 'app-shell', 'page-header', 'object-page', 'action-bar', 'card', 'descriptions']],
  ['Điều hướng', ['tabs', 'pagination']],
  ['Hiển thị dữ liệu', ['table', 'tag', 'avatar', 'progress', 'timeline', 'icon', 'skeleton']],
  ['Phản hồi và lớp phủ', ['alert', 'toast', 'dialog', 'drawer', 'popover', 'tooltip', 'empty-state']],
  ['Tiện ích', ['format']],
];

// Entry points whose docs live in several pages or in a foundation page.
const DESCRIPTION_OVERRIDE = {
  layout:
    'Xếp dọc có khoảng cách đều theo mật độ (`nxt-stack`), xếp ngang tự xuống dòng (`nxt-inline`), lưới 12 cột phản hồi theo bề rộng của chính nó (`nxt-grid`, `nxtSpan`), thay cho margin viết tay.',
};
const DOC_FALLBACK = { format: 'apps/docs/src/content/foundations/formatting.md' };

const json = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const repoUrl = json('packages/tokens/package.json').repository.url.replace(/^git\+/, '').replace(/\.git$/, '');
const blob = `${repoUrl}/blob/main`;

const entries = fs
  .readdirSync('packages/ui', { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== 'src' && fs.existsSync(path.join('packages/ui', d.name, 'public-api.ts')))
  .map((d) => d.name)
  .sort();

const grouped = GROUPS.flatMap(([, names]) => names);
const missing = entries.filter((n) => !grouped.includes(n));
const stale = grouped.filter((n) => !entries.includes(n));
if (missing.length || stale.length) {
  console.error(`readme-catalog: edit GROUPS in tools/docs/readme-catalog.mjs. Not in any group: ${missing.join(', ') || '-'}; no longer exist: ${stale.join(', ') || '-'}.`);
  process.exit(1);
}

function frontmatter(file) {
  if (!fs.existsSync(file)) return {};
  const block = fs.readFileSync(file, 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1] ?? '';
  return Object.fromEntries([...block.matchAll(/^(\w+):\s*(.+)$/gm)].map((m) => [m[1], m[2].trim()]));
}

/** `NxtFormField` for `form-field`; falls back to the exported classes (layout, app-shell…). */
function importNames(name) {
  const api = fs.readFileSync(path.join('packages/ui', name, 'public-api.ts'), 'utf8');
  const exported = [...api.matchAll(/^export\s+\{([^}]+)\}\s+from/gm)].flatMap((m) => m[1].split(',').map((s) => s.trim()).filter(Boolean));
  const classes = exported.filter((s) => /^Nxt[A-Z]/.test(s));
  const main = `Nxt${name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')}`;
  if (classes.includes(main)) return main;
  return classes.slice(0, 5).join(', ') || '(pipe, hàm)';
}

const oneLine = (s) => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').replace(/\.$/, '');

const lines = [BEGIN, ''];
for (const [title, names] of GROUPS) {
  lines.push(`**${title}**`, '', '| Entry point | Import | Dùng để |', '|-------------|--------|---------|');
  for (const name of names) {
    const fm = frontmatter(DOC_FALLBACK[name] ?? `apps/docs/src/content/components/${name}.md`);
    const description = oneLine(DESCRIPTION_OVERRIDE[name] ?? fm.description ?? '');
    if (!description) {
      console.error(`readme-catalog: no description for ${name} (docs frontmatter missing).`);
      process.exit(1);
    }
    const draft = fm.status === 'draft' ? ' *(bản nháp)*' : '';
    lines.push(`| [\`@nxt/ui/${name}\`](${blob}/packages/ui/${name}/SPEC.md) | \`${importNames(name)}\` | ${description}${draft} |`);
  }
  lines.push('');
}
lines.push(END);
const block = lines.join('\n');

const current = fs.readFileSync(README, 'utf8');
const start = current.indexOf(BEGIN);
const end = current.indexOf(END);
if (start < 0 || end < 0) {
  console.error(`readme-catalog: ${README} has no ${BEGIN} … ${END} block.`);
  process.exit(1);
}
const next = current.slice(0, start) + block + current.slice(end + END.length);

if (process.argv.includes('--check')) {
  if (next.replace(/\r\n/g, '\n') !== current.replace(/\r\n/g, '\n')) {
    console.error('readme-catalog: the component catalog in packages/ui/README.md is stale. Run: npm run readme:catalog');
    process.exit(1);
  }
  console.log(`readme-catalog: OK (${entries.length} entry points in ${GROUPS.length} groups).`);
} else {
  fs.writeFileSync(README, next);
  console.log(`readme-catalog: wrote ${entries.length} entry points in ${GROUPS.length} groups to ${README}.`);
}
