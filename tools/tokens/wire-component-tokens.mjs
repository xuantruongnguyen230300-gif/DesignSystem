#!/usr/bin/env node
// Wire each component stylesheet to the generated token file(s) of the component tokens it uses.
//
//   node tools/tokens/wire-component-tokens.mjs            add/refresh the import block in every component CSS
//   node tools/tokens/wire-component-tokens.mjs --check    fail if a block is missing or out of date (used by ds:check)
//   node tools/tokens/wire-component-tokens.mjs --skip a,b leave the listed packages/ui/<entry> folders alone
//
// Why: `@nxt/tokens/css/core.css` carries the shared tokens; the token aliases of one component
// (`--nxt-button-*`) are generated into `packages/tokens/dist/css/components/button.css` and imported by
// `button.css`, so an app that imports only `@nxt/ui/button` loads only the button's tokens.
// The import is inlined by the Angular build, so published components need no extra stylesheet.

import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const check = args.includes('--check');
const skipArg = args.indexOf('--skip');
const skip = new Set(skipArg >= 0 ? args[skipArg + 1].split(',') : []);

const tokensDir = 'packages/tokens/src/component';
// Component names are the keys under `component` in the token files (a file may define several, e.g.
// layout.tokens.json defines `flow`), not the file names.
const names = [
  ...new Set(
    fs
      .readdirSync(tokensDir)
      .filter((f) => f.endsWith('.tokens.json'))
      .flatMap((f) => Object.keys(JSON.parse(fs.readFileSync(path.join(tokensDir, f), 'utf8')).component ?? {})),
  ),
].sort((a, b) => b.length - a.length); // longest first: `date-picker` before `date`

const BEGIN = '/* nxt-tokens:begin (generated by tools/tokens/wire-component-tokens.mjs, do not edit) */';
const END = '/* nxt-tokens:end */';
function stripBlocks(css) {
  let out = css;
  for (let i = out.indexOf(BEGIN); i >= 0; i = out.indexOf(BEGIN)) {
    const end = out.indexOf(END, i);
    if (end < 0) break;
    const rest = out.slice(end + END.length);
    out = out.slice(0, i) + (rest.startsWith('\n') ? rest.slice(1) : rest);
  }
  return out;
}

function used(css) {
  const found = new Set();
  for (const m of css.matchAll(/--nxt-([a-z0-9-]+?)-[a-z0-9-]+/g)) {
    const full = m[0].slice('--nxt-'.length);
    const name = names.find((n) => full.startsWith(`${n}-`));
    if (name) found.add(name);
  }
  return [...found].sort();
}

let changed = 0;
const problems = [];
for (const entry of fs.readdirSync('packages/ui')) {
  if (skip.has(entry)) continue;
  const src = path.join('packages/ui', entry, 'src');
  if (!fs.existsSync(src)) continue;
  for (const f of fs.readdirSync(src).filter((x) => x.endsWith('.css'))) {
    const file = path.join(src, f);
    const css = fs.readFileSync(file, 'utf8');
    const body = stripBlocks(css);
    const comps = used(body);
    const rel = (c) => `${path.relative(path.dirname(file), 'packages/tokens/dist/css/components').split(path.sep).join('/')}/${c}.css`;
    const block = comps.length ? `${BEGIN}\n${comps.map((c) => `@import '${rel(c)}';`).join('\n')}\n${END}\n` : '';
    const next = block + body;
    if (next === css) continue;
    if (check) problems.push(`${file}: token import block is ${css.includes(BEGIN) ? 'out of date' : 'missing'}`);
    else {
      fs.writeFileSync(file, next);
      changed++;
    }
  }
}
if (check) {
  if (problems.length) {
    console.error(problems.join('\n'));
    console.error('Run: node tools/tokens/wire-component-tokens.mjs');
    process.exit(1);
  }
  console.log('wire-component-tokens: all component stylesheets import their tokens.');
} else console.log(`wire-component-tokens: updated ${changed} file(s).`);
