#!/usr/bin/env node
// Generate an 11-step OKLCH color scale (50…950) from one seed color, gamut-mapped to sRGB,
// as W3C DTCG primitive tokens, plus a WCAG contrast report for every step.
//
// Usage: node tools/tokens/palette.mjs --name teal --seed "#0F766E" [--out file.json] [--no-anchor] [--json]
//   --name       scale name, kebab-case (becomes primitive.color.<name>.<step>)
//   --seed       any CSS color: #hex, rgb(), oklch()
//   --out        write DTCG JSON to this file (refuses to overwrite an existing file)
//   --no-anchor  do not snap the nearest step to the exact seed color
//   --json       print the DTCG JSON to stdout instead of the report

import fs from 'node:fs';
import path from 'node:path';
import { contrastRatio, gamutMapOklch, oklchToSrgb, parseColor, srgbToOklch, toHex } from '../lib/color.mjs';

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
// Lightness and relative-chroma curves calibrated on widely used UI scales (Tailwind v4 style).
const LIGHTNESS = [0.971, 0.936, 0.885, 0.808, 0.704, 0.623, 0.546, 0.488, 0.424, 0.379, 0.282];
const CHROMA = [0.057, 0.131, 0.241, 0.429, 0.673, 0.873, 1, 0.992, 0.812, 0.596, 0.371];
const NEUTRAL_THRESHOLD = 0.03; // seeds below this chroma become a near-neutral scale

const args = process.argv.slice(2);
const opt = (n) => {
  const i = args.indexOf(n);
  return i >= 0 ? args[i + 1] : undefined;
};
const name = opt('--name');
const seedStr = opt('--seed');
const out = opt('--out');
const anchor = !args.includes('--no-anchor');

if (!name || !seedStr || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) {
  console.error('Usage: node tools/tokens/palette.mjs --name <kebab-name> --seed <css-color> [--out file] [--no-anchor] [--json]');
  process.exit(2);
}
const seed = parseColor(seedStr);
if (!seed) {
  console.error(`Cannot parse seed color: ${seedStr}`);
  process.exit(2);
}

const s = srgbToOklch(seed);
const nearest = LIGHTNESS.reduce((best, L, i) => (Math.abs(L - s.L) < Math.abs(LIGHTNESS[best] - s.L) ? i : best), 0);
const neutral = s.C < NEUTRAL_THRESHOLD;
const peak = neutral ? s.C : Math.min(0.37, s.C / CHROMA[nearest]);

const round = (x, d) => Math.round(x * 10 ** d) / 10 ** d;
const scale = STEPS.map((step, i) => {
  let L = LIGHTNESS[i];
  let C = neutral ? s.C * (i === 0 || i === STEPS.length - 1 ? 0.6 : 1) : peak * CHROMA[i];
  let H = s.H;
  if (anchor && i === nearest) ({ L, C, H } = s);
  const mapped = gamutMapOklch(L, C, H);
  const rgb = oklchToSrgb(mapped.L, mapped.C, mapped.H);
  return { step, L: round(mapped.L, 4), C: round(mapped.C, 4), H: round(mapped.H, 2), hex: toHex(rgb), rgb, anchored: anchor && i === nearest, clipped: mapped.C + 1e-4 < C };
});

const tokens = {
  primitive: {
    color: {
      $type: 'color',
      [name]: Object.fromEntries(
        scale.map((c) => [
          String(c.step),
          { $value: { colorSpace: 'oklch', components: [c.L, c.C, c.H], alpha: 1, hex: c.hex } },
        ]),
      ),
    },
  },
};
tokens.primitive.color[name].$description = `Generated by tools/tokens/palette.mjs from seed ${seedStr} (anchored at ${STEPS[nearest]}${anchor ? '' : ', not snapped'}).`;

if (out) {
  const file = path.resolve(out);
  if (fs.existsSync(file)) {
    console.error(`Refusing to overwrite ${out} — merge the scale by hand or choose another path.`);
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(tokens, null, 2)}\n`);
}

if (args.includes('--json')) {
  console.log(JSON.stringify(tokens, null, 2));
  process.exit(0);
}

const white = { r: 1, g: 1, b: 1, alpha: 1 };
const ink = parseColor('#0A0A0A');
console.log(`Scale "${name}" from ${seedStr} → oklch(${round(s.L, 3)} ${round(s.C, 3)} ${round(s.H, 1)})${neutral ? ' [neutral]' : ''}`);
console.log('step  hex       oklch                     vs white  vs ink   text-on');
let fill = null;
for (const c of scale) {
  const w = contrastRatio(white, c.rgb);
  const k = contrastRatio(ink, c.rgb);
  if (!fill && c.step >= 500 && w >= 4.5) fill = c.step;
  const on = w >= 4.5 ? 'white' : k >= 4.5 ? 'ink' : 'none (large/non-text only)';
  const flags = [c.anchored ? 'seed' : '', c.clipped ? 'gamut-clipped' : ''].filter(Boolean).join(',');
  console.log(
    `${String(c.step).padEnd(5)} ${c.hex}  ${`oklch(${c.L} ${c.C} ${c.H})`.padEnd(25)} ${w.toFixed(2).padStart(6)}  ${k.toFixed(2).padStart(6)}   ${on}${flags ? `  [${flags}]` : ''}`,
  );
}
console.log(fill ? `Suggested solid fill with white text: ${name}.${fill} (first step ≥ 500 reaching 4.5:1)` : 'No step ≥ 500 reaches 4.5:1 with white text — use dark text on fills or darken the seed.');
if (out) console.log(`Wrote ${out}`);
