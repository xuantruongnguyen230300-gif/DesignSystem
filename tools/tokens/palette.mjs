#!/usr/bin/env node
// Generate OKLCH color scales (50…950), gamut-mapped to sRGB, as W3C DTCG primitive tokens.
//
// Single scale (report + optional file):
//   node tools/tokens/palette.mjs --name teal --seed "#0F766E" [--out file.json] [--no-anchor] [--neutral] [--json]
// Batch (regenerates the primitive color file from a seeds config):
//   node tools/tokens/palette.mjs --config packages/tokens/palettes.json
//
//   --name       scale name, kebab-case (becomes primitive.color.<name>.<step>)
//   --seed       any CSS color: #hex, rgb(), oklch()
//   --out        write DTCG JSON to this file (refuses to overwrite an existing file)
//   --no-anchor  do not snap the nearest step to the exact seed color
//   --neutral    force the neutral lightness curve (auto when seed chroma < 0.03)
//   --json       print the DTCG JSON to stdout instead of the report
//   --config     batch mode; the output file is generated — edit the config, not the output

import fs from 'node:fs';
import path from 'node:path';
import { contrastRatio, parseColor } from '../lib/color.mjs';
import { generateScale, scaleToDtcg } from '../lib/palette.mjs';

const args = process.argv.slice(2);
const opt = (n) => {
  const i = args.indexOf(n);
  return i >= 0 ? args[i + 1] : undefined;
};
const NAME_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const configPath = opt('--config');
if (configPath) {
  runBatch(configPath);
} else {
  runSingle();
}

function runBatch(file) {
  const cfgFile = path.resolve(file);
  const cfg = JSON.parse(fs.readFileSync(cfgFile, 'utf8'));
  const out = path.resolve(path.dirname(cfgFile), cfg.out);
  const color = { $type: 'color', $description: `GENERATED by tools/tokens/palette.mjs from ${path.basename(cfgFile)} — do not edit by hand.` };
  for (const [name, def] of Object.entries(cfg.scales)) {
    if (!NAME_RE.test(name)) throw new Error(`Invalid scale name "${name}"`);
    const scale = generateScale(def.seed, { anchor: def.anchor ?? true, neutral: def.neutral });
    color[name] = scaleToDtcg(scale, def.description ?? `Seed ${def.seed} (anchored at ${scale.anchorStep}).`);
    const clipped = scale.steps.filter((s) => s.clipped).map((s) => s.step);
    console.log(`${name.padEnd(10)} seed ${def.seed.padEnd(26)} anchor ${scale.anchorStep}${clipped.length ? `  gamut-clipped: ${clipped.join(',')}` : ''}`);
  }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${JSON.stringify({ primitive: { color } }, null, 2)}\n`);
  console.log(`Wrote ${path.relative(process.cwd(), out).split(path.sep).join('/')}`);
}

function runSingle() {
  const name = opt('--name');
  const seedStr = opt('--seed');
  const out = opt('--out');
  if (!name || !seedStr || !NAME_RE.test(name)) {
    console.error('Usage: node tools/tokens/palette.mjs --name <kebab-name> --seed <css-color> [--out file] [--no-anchor] [--neutral] [--json]');
    console.error('       node tools/tokens/palette.mjs --config packages/tokens/palettes.json');
    process.exit(2);
  }
  let scale;
  try {
    scale = generateScale(seedStr, { anchor: !args.includes('--no-anchor'), neutral: args.includes('--neutral') || undefined });
  } catch (e) {
    console.error(e.message);
    process.exit(2);
  }
  const tokens = {
    primitive: { color: { $type: 'color', [name]: scaleToDtcg(scale, `Generated by tools/tokens/palette.mjs from seed ${seedStr} (anchored at ${scale.anchorStep}).`) } },
  };

  if (out) {
    const file = path.resolve(out);
    if (fs.existsSync(file)) {
      console.error(`Refusing to overwrite ${out} — merge the scale by hand or choose another path.`);
      process.exit(1);
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, `${JSON.stringify(tokens, null, 2)}\n`);
  }

  if (args.includes('--json')) {
    console.log(JSON.stringify(tokens, null, 2));
    return;
  }

  const white = { r: 1, g: 1, b: 1, alpha: 1 };
  const ink = parseColor('#0A0A0A');
  const s = scale.seed;
  const r3 = (x) => Math.round(x * 1000) / 1000;
  console.log(`Scale "${name}" from ${seedStr} → oklch(${r3(s.L)} ${r3(s.C)} ${Math.round(s.H * 10) / 10})${scale.neutral ? ' [neutral]' : ''}`);
  console.log('step  hex       oklch                     vs white  vs ink   text-on');
  let fill = null;
  for (const c of scale.steps) {
    const w = contrastRatio(white, c.rgb);
    const k = contrastRatio(ink, c.rgb);
    if (!fill && c.step >= 500 && w >= 4.5) fill = c.step;
    const on = w >= 4.5 ? 'white' : k >= 4.5 ? 'ink' : 'none (large/non-text only)';
    const flags = [c.anchored ? 'seed' : '', c.clipped ? 'gamut-clipped' : ''].filter(Boolean).join(',');
    console.log(
      `${String(c.step).padEnd(5)} ${c.hex}  ${`oklch(${c.L} ${c.C} ${c.H})`.padEnd(25)} ${w.toFixed(2).padStart(6)}  ${k.toFixed(2).padStart(6)}   ${on}${flags ? `  [${flags}]` : ''}`,
    );
  }
  console.log(fill ? `Suggested solid fill with white text: ${name}.${fill} (first step ≥ 500 reaching 4.5:1)` : 'No step ≥ 500 reaches 4.5:1 with white text — use dark text on fills or darken the seed.');
  if (out) console.log(`Wrote ${out}`);
}
