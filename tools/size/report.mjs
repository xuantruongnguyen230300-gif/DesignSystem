#!/usr/bin/env node
// Size gate: measures gzip size of the token CSS (core, full bundle, each component) and of every built
// @nxt/ui entry point (JS), compares with tools/size/budgets.json and fails when something grows.
//
//   npm run size:check            report + fail over budget
//   npm run size:check -- --update   rewrite budgets.json from the current build (+10% headroom)
//
// Run after `npm run build`. Budgets are in bytes of gzip output.

import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const root = process.cwd();
const gz = (file) => zlib.gzipSync(fs.readFileSync(file), { level: 9 }).length;
const raw = (file) => fs.statSync(file).size;
const budgetFile = path.join(root, 'tools/size/budgets.json');
const update = process.argv.includes('--update');

const cssDir = path.join(root, 'packages/tokens/dist/css');
const fesmDir = path.join(root, 'dist/ui/fesm2022');
for (const [label, p] of [['token CSS', cssDir], ['@nxt/ui build', fesmDir]]) {
  if (!fs.existsSync(p)) {
    console.error(`Missing ${label} at ${path.relative(root, p)}. Run npm run build first.`);
    process.exit(1);
  }
}

const measured = { css: {}, components: {}, entries: {} };
for (const name of ['core.css', 'nxt.css']) measured.css[name] = { raw: raw(path.join(cssDir, name)), gzip: gz(path.join(cssDir, name)) };
const compDir = path.join(cssDir, 'components');
for (const f of fs.readdirSync(compDir).filter((x) => x.endsWith('.css')).sort()) {
  measured.components[f] = { raw: raw(path.join(compDir, f)), gzip: gz(path.join(compDir, f)) };
}
for (const f of fs.readdirSync(fesmDir).filter((x) => x.endsWith('.mjs')).sort()) {
  measured.entries[f] = { raw: raw(path.join(fesmDir, f)), gzip: gz(path.join(fesmDir, f)) };
}

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
const compTotal = Object.values(measured.components).reduce((s, c) => s + c.gzip, 0);
const biggestComp = Object.entries(measured.components).sort((a, b) => b[1].gzip - a[1].gzip)[0];
const biggestEntry = Object.entries(measured.entries).sort((a, b) => b[1].gzip - a[1].gzip)[0];
console.log('Token CSS (gzip)');
console.log(`  core.css            ${kb(measured.css['core.css'].gzip).padStart(9)}  (raw ${kb(measured.css['core.css'].raw)})`);
console.log(`  nxt.css (full)      ${kb(measured.css['nxt.css'].gzip).padStart(9)}  (raw ${kb(measured.css['nxt.css'].raw)})`);
console.log(`  components/*.css    ${kb(compTotal).padStart(9)}  for ${Object.keys(measured.components).length} files; largest ${biggestComp[0]} ${kb(biggestComp[1].gzip)}`);
console.log(`@nxt/ui entries (gzip): ${Object.keys(measured.entries).length} files; largest ${biggestEntry[0]} ${kb(biggestEntry[1].gzip)}`);

const current = {
  coreCssGzip: measured.css['core.css'].gzip,
  fullCssGzip: measured.css['nxt.css'].gzip,
  componentCssMaxGzip: biggestComp[1].gzip,
  entryMaxGzip: biggestEntry[1].gzip,
  entries: Object.fromEntries(Object.entries(measured.entries).map(([k, v]) => [k, v.gzip])),
};
const headroom = (n) => Math.ceil(n * 1.1);

if (update) {
  const budgets = {
    _note: 'Gzip bytes. Generated by npm run size:check -- --update (current + 10%). Lower these when a refactor makes things smaller; never raise without a reason.',
    coreCssGzip: headroom(current.coreCssGzip),
    fullCssGzip: headroom(current.fullCssGzip),
    componentCssMaxGzip: headroom(current.componentCssMaxGzip),
    entryMaxGzip: headroom(current.entryMaxGzip),
    entries: Object.fromEntries(Object.entries(current.entries).map(([k, v]) => [k, headroom(v)])),
  };
  fs.writeFileSync(budgetFile, `${JSON.stringify(budgets, null, 2)}\n`);
  console.log(`Wrote ${path.relative(root, budgetFile)}`);
  process.exit(0);
}

if (!fs.existsSync(budgetFile)) {
  console.error('No tools/size/budgets.json. Run: npm run size:check -- --update');
  process.exit(1);
}
const budgets = JSON.parse(fs.readFileSync(budgetFile, 'utf8'));
const failures = [];
for (const k of ['coreCssGzip', 'fullCssGzip', 'componentCssMaxGzip', 'entryMaxGzip']) {
  if (current[k] > budgets[k]) failures.push(`${k}: ${current[k]} B > budget ${budgets[k]} B`);
}
for (const [k, v] of Object.entries(current.entries)) {
  const b = budgets.entries?.[k];
  if (b === undefined) failures.push(`new entry ${k} (${v} B) has no budget; run size:check -- --update`);
  else if (v > b) failures.push(`${k}: ${v} B > budget ${b} B`);
}
if (failures.length) {
  console.error(`\nSize budget exceeded (${failures.length}):`);
  for (const f of failures) console.error(`  ${f}`);
  process.exit(1);
}
console.log('\nSize budgets: all within limits.');
